// Generates supabase/seed.sql from the demo data in src/data/seed.ts and src/config/countries.ts.
//   npm run seed:sql
// Run the resulting file in the Supabase SQL editor AFTER the migrations. It is idempotent (upserts).
import { writeFileSync } from "node:fs";
import { defaultCountries } from "../src/config/countries.ts";
import { seedBrands, seedCategories, seedProducts, seedPromotions } from "../src/data/seed.ts";

const q = (v: string | null | undefined) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const n = (v: number | null | undefined) => (v === null || v === undefined ? "null" : String(v));
const arr = (a: string[]) => `array[${a.map(q).join(", ")}]::text[]`;
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const b = (v: boolean) => (v ? "true" : "false");

const out: string[] = [
  "-- GENERATED by `npm run seed:sql` from src/data/seed.ts — do not edit by hand.",
  "-- Demo data: every product, price and promotion is sample data (is_demo = true).",
  "begin;",
  "",
  "-- countries",
];

for (const c of Object.values(defaultCountries)) {
  out.push(
    `insert into public.countries (code, name_en, name_ar, currency, currency_decimals, whatsapp_number, phone, phone_display, email, address_en, address_ar, maps_link, maps_embed, delivery_info_en, delivery_info_ar, delivery_fee, free_delivery_over, regions, hours, open_days, open_hour, close_hour, time_zone, enabled)
values (${q(c.code)}, ${q(c.name.en)}, ${q(c.name.ar)}, ${q(c.currency)}, ${c.currencyDecimals}, ${q(c.whatsappNumber)}, ${q(c.phone)}, ${q(c.phoneDisplay)}, ${q(c.email)}, ${q(c.address.en)}, ${q(c.address.ar)}, ${q(c.mapsLink)}, ${q(c.mapsEmbed)}, ${q(c.deliveryInfo.en)}, ${q(c.deliveryInfo.ar)}, ${c.deliveryFee}, ${n(c.freeDeliveryOver)}, ${json(c.regions)}, ${json(c.hours)}, array[${c.openDays.join(", ")}]::smallint[], ${c.openHour}, ${c.closeHour}, ${q(c.timeZone)}, ${b(c.enabled)})
on conflict (code) do nothing; -- never overwrite settings staff have already edited`,
  );
}

out.push("", "-- categories (parents first; requires migration 20261022000200_category_hierarchy.sql)");
// Parents before children, at any depth. A re-run never blanks an Arabic name that staff have already entered.
const depth = (slug: string): number => {
  const c = seedCategories.find((x) => x.slug === slug);
  return c?.parent ? 1 + depth(c.parent) : 0;
};
for (const c of [...seedCategories].sort((a, z) => depth(a.slug) - depth(z.slug) || a.sort - z.sort)) {
  out.push(
    `insert into public.categories (slug, name_en, name_ar, parent_slug, sort, active) values (${q(c.slug)}, ${q(c.name.en)}, ${q(c.name.ar)}, ${q(c.parent)}, ${c.sort}, ${b(c.active)}) on conflict (slug) do update set name_en = excluded.name_en, name_ar = case when excluded.name_ar = '' then public.categories.name_ar else excluded.name_ar end, parent_slug = excluded.parent_slug, sort = excluded.sort, active = excluded.active;`,
  );
}

out.push("", "-- brands");
for (const br of seedBrands) {
  out.push(`insert into public.brands (slug, name, is_demo) values (${q(br.slug)}, ${q(br.name)}, ${b(br.isDemo)}) on conflict (slug) do update set name = excluded.name, is_demo = excluded.is_demo;`);
}

out.push("", "-- products");
for (const p of seedProducts) {
  out.push(
    `insert into public.products (id, sku, name_en, name_ar, brand_slug, category_slug, subcategory_slug, condition, grade, description_en, description_ar, specs_en, specs_ar, images, warranty_en, warranty_ar, featured, active, is_demo, created_at)
values (${q(p.id)}, ${q(p.sku)}, ${q(p.name.en)}, ${q(p.name.ar)}, ${q(p.brand)}, ${q(p.category)}, ${q(p.subcategory)}, ${q(p.condition)}, ${q(p.grade)}, ${q(p.description.en)}, ${q(p.description.ar)}, ${arr(p.specs.en)}, ${arr(p.specs.ar)}, ${arr(p.images)}, ${q(p.warranty.en)}, ${q(p.warranty.ar)}, ${b(p.featured)}, ${b(p.active)}, ${b(p.isDemo)}, ${q(p.createdAt)})
on conflict (id) do nothing; -- re-running never overwrites products edited in Admin`,
  );
  for (const [country, row] of Object.entries(p.prices)) {
    out.push(
      `insert into public.product_prices (product_id, country_code, price, compare_at, stock, available) values (${q(p.id)}, ${q(country)}, ${row.price}, ${n(row.compareAt)}, ${row.stock}, ${b(row.available)}) on conflict (product_id, country_code) do nothing;`,
    );
  }
}

out.push("", "-- promotions");
for (const pr of seedPromotions) {
  out.push(
    `insert into public.promotions (id, title_en, title_ar, subtitle_en, subtitle_ar, image_url, link_path, discount_percent, scope, scope_value, country_code, starts_at, ends_at, active, sort) values (${q(pr.id)}, ${q(pr.title.en)}, ${q(pr.title.ar)}, ${q(pr.subtitle.en)}, ${q(pr.subtitle.ar)}, ${q(pr.imageUrl)}, ${q(pr.linkPath)}, ${pr.discountPercent}, ${q(pr.scope)}, ${q(pr.scopeValue)}, ${q(pr.country)}, ${q(pr.startsAt)}, ${q(pr.endsAt)}, ${b(pr.active)}, ${pr.sort}) on conflict (id) do nothing;`,
  );
}

out.push("", "commit;", "");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"));
console.log(`supabase/seed.sql written: ${seedProducts.length} products, ${seedCategories.length} categories, ${seedBrands.length} brands`);
